//! Generate Rust protocol types from `codex app-server generate-json-schema` output.
//!
//! ```sh
//! codex app-server generate-json-schema --out /tmp/codex-schema
//! cargo run -p codex-client-cw --bin protocol-codegen -- /tmp/codex-schema src/generated
//! ```
//!
//! Generated output is checked in. Consumers do not need the Codex CLI, and generation
//! does not run during builds. Re-run this program after upgrading Codex.

mod render;
mod schema;

use anyhow::{Context, Result};
use render::{Renderer, doc_comment, field_name, pascal, type_name};
use schema::{Schema, reference_name};
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

/// Methods whose response type cannot be inferred by convention, excluding nullary
/// requests (`params` is `{"type":"null"}`). The key is the request params type name or
/// method name; the value is the response type name.
///
/// The schema does not express these associations: `ts-rs` exports types but does not
/// map requests to responses. Infer by name and list exceptions here.
const RESPONSE_OVERRIDES: &[(&str, &str)] = &[
    ("account/gatewayOAuth/read", "GatewayOAuthReadResponse"),
    ("account/gatewayOAuth/login", "GatewayOAuthLoginResponse"),
    ("account/gatewayOAuth/cancel", "GatewayOAuthCancelResponse"),
    ("account/logout", "LogoutAccountResponse"),
    ("account/rateLimits/read", "GetAccountRateLimitsResponse"),
    ("account/usage/read", "GetAccountTokenUsageResponse"),
    (
        "account/workspaceMessages/read",
        "GetWorkspaceMessagesResponse",
    ),
    ("config/mcpServer/reload", "McpServerRefreshResponse"),
    ("config/batchWrite", "ConfigWriteResponse"),
    ("config/value/write", "ConfigWriteResponse"),
    ("configRequirements/read", "ConfigRequirementsReadResponse"),
    (
        "externalAgentConfig/import/readHistories",
        "ExternalAgentConfigImportHistoriesReadResponse",
    ),
    (
        "windowsSandbox/readiness",
        "WindowsSandboxReadinessResponse",
    ),
];

const HEADER: &str = "// Generated by protocol-codegen; do not edit by hand.\n\
                      // Regenerate with:\n\
                      //   codex app-server generate-json-schema --out <dir>\n\
                      //   cargo run -p codex-client-cw --bin protocol-codegen -- <dir> src/generated\n\n";

fn main() -> Result<()> {
    let mut args = std::env::args().skip(1);
    let schema_dir = PathBuf::from(
        args.next()
            .context("usage: protocol-codegen <schema directory> <output directory>")?,
    );
    let out_dir = PathBuf::from(args.next().context("missing output directory argument")?);

    let (definitions, roots) = load(&schema_dir)?;
    println!("Read {} type definitions", definitions.len());

    let known: BTreeSet<String> = definitions.keys().map(|name| type_name(name)).collect();
    let mut renderer = Renderer::new(known);

    // 1. All data types.
    let mut body = String::new();
    for (name, schema) in &definitions {
        body.push_str(&renderer.definition(name, schema));
        body.push('\n');
    }
    // Generate inline types derived during rendering as well. They may derive more types,
    // so continue until reaching a fixed point.
    while !renderer.pending.is_empty() {
        let batch = std::mem::take(&mut renderer.pending);
        for pending in batch {
            body.push_str(&renderer.definition(&pending.name, &pending.schema));
            body.push('\n');
        }
    }
    let types = format!(
        "{HEADER}//! All data types in the protocol.\n\n\
         #![allow(clippy::large_enum_variant)]\n\n\
         use serde::{{Deserialize, Serialize}};\n\n{body}"
    );

    // 2. Requests: method → (params, response).
    let client_request = roots
        .get("ClientRequest")
        .context("ClientRequest.json is missing from the schema directory")?;
    let (methods, request_surface) = render_requests(client_request, &definitions)?;

    // 3. Server notifications and server requests.
    let (notifications, notification_surface) = render_incoming(
        "ServerNotification",
        roots
            .get("ServerNotification")
            .context("ServerNotification.json is missing")?,
        "Server-pushed notification. No reply is required.",
    )?;
    let (server_requests, server_request_surface) = render_incoming(
        "ServerRequest",
        roots
            .get("ServerRequest")
            .context("ServerRequest.json is missing")?,
        "Server-initiated request. **A reply is required** or the server will remain blocked.",
    )?;

    std::fs::create_dir_all(&out_dir)?;
    write(&out_dir.join("types.rs"), &types)?;
    write(&out_dir.join("methods.rs"), &methods)?;
    write(
        &out_dir.join("events.rs"),
        &format!(
            "{HEADER}//! Typed wrappers for inbound messages.\n\n\
             use super::types::*;\n\
             use serde::{{Deserialize, Serialize}};\n\n{notifications}\n{server_requests}"
        ),
    )?;
    write(
        &out_dir.with_extension("rs"),
        &format!(
            "{HEADER}//! Protocol definitions generated from JSON Schema.\n\
             //!\n\
             //! These types cover the complete App Server protocol surface: `types` contains\n\
             //! data types, `methods` maps client requests to method and parameter/response\n\
             //! types, and `events` contains server notifications and requests.\n\n\
             pub mod events;\n\
             pub mod methods;\n\
             pub mod types;\n"
        ),
    )?;
    write(
        &out_dir.join("SURFACE.md"),
        &surface(
            &request_surface,
            &notification_surface,
            &server_request_surface,
            &definitions,
        ),
    )?;
    println!("Wrote generated files to {}", out_dir.display());
    Ok(())
}

fn write(path: &Path, contents: &str) -> Result<()> {
    let contents = format!("{}\n", contents.trim_end());
    std::fs::write(path, &contents).with_context(|| format!("writing {}", path.display()))?;
    // Keep generated files rustfmt-clean so regeneration does not add unrelated diffs
    // that obscure actual protocol changes.
    if path.extension().is_some_and(|ext| ext == "rs") {
        match std::process::Command::new("rustfmt")
            .args(["--edition", "2024"])
            .arg(path)
            .status()
        {
            Ok(status) if status.success() => {}
            Ok(status) => println!(
                "  warning: rustfmt exited with {status}; {} was not formatted",
                path.display()
            ),
            Err(error) => println!(
                "  warning: rustfmt not found ({error}); {} was not formatted",
                path.display()
            ),
        }
    }
    println!("  {} ({} bytes)", path.display(), contents.len());
    Ok(())
}

/// Read all single-type files in the schema directory and merge their definitions.
///
/// Each file is self-contained (root schema plus all referenced definitions), so a
/// definition may appear in multiple files. Duplicates represent the same Rust type; keep
/// the first one encountered.
fn load(dir: &Path) -> Result<(BTreeMap<String, Schema>, BTreeMap<String, Schema>)> {
    let mut definitions: BTreeMap<String, Schema> = BTreeMap::new();
    let mut roots: BTreeMap<String, Schema> = BTreeMap::new();
    let mut files = Vec::new();
    collect_files(dir, &mut files)?;
    files.sort();

    for file in files {
        let name = file
            .file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or_default()
            .to_owned();
        // The single-type files already cover these aggregate files; skip them to avoid
        // duplicate definitions.
        if name.starts_with("codex_app_server_protocol") {
            continue;
        }
        let text = std::fs::read_to_string(&file)?;
        let mut raw: serde_json::Value =
            serde_json::from_str(&text).with_context(|| format!("reading {}", file.display()))?;
        normalize(&mut raw);
        let schema: Schema =
            serde_json::from_value(raw).with_context(|| format!("parsing {}", file.display()))?;
        for (definition, sub) in &schema.definitions {
            definitions
                .entry(definition.clone())
                .or_insert_with(|| sub.clone());
        }
        let mut root = schema.clone();
        root.definitions = BTreeMap::new();
        let root_name = root.title.clone().unwrap_or_else(|| name.clone());
        definitions
            .entry(root_name.clone())
            .or_insert_with(|| root.clone());
        roots.insert(root_name, root);
    }
    Ok((definitions, roots))
}

/// JSON Schema allows bare `true`/`false` values for schemas matching anything or nothing,
/// such as an MCP tool's `inputSchema`. Normalize bare booleans in schema positions to
/// empty objects so they can be handled as ordinary schemas (an empty schema maps to
/// `serde_json::Value`).
///
/// `additionalProperties` is excluded because booleans have a separate meaning there and
/// are handled by the renderer.
fn normalize(value: &mut serde_json::Value) {
    const SCHEMA_MAPS: &[&str] = &["properties", "definitions", "patternProperties"];
    const SCHEMA_VALUES: &[&str] = &["items", "additionalItems", "not", "if", "then", "else"];
    const SCHEMA_LISTS: &[&str] = &["oneOf", "anyOf", "allOf"];

    let serde_json::Value::Object(object) = value else {
        return;
    };
    for (key, child) in object.iter_mut() {
        if SCHEMA_MAPS.contains(&key.as_str()) {
            if let serde_json::Value::Object(entries) = child {
                for entry in entries.values_mut() {
                    normalize_schema(entry);
                }
            }
        } else if SCHEMA_VALUES.contains(&key.as_str()) {
            normalize_schema(child);
        } else if SCHEMA_LISTS.contains(&key.as_str()) {
            if let serde_json::Value::Array(items) = child {
                for item in items {
                    normalize_schema(item);
                }
            }
        } else if key == "additionalProperties" && child.is_object() {
            normalize(child);
        }
    }
}

fn normalize_schema(value: &mut serde_json::Value) {
    if value.is_boolean() {
        *value = serde_json::json!({});
        return;
    }
    normalize(value);
}

fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect_files(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "json") {
            out.push(path);
        }
    }
    Ok(())
}

/// Generate one `Request` implementation per client request, implemented on the
/// **parameter type itself**.
///
/// The parameter type uniquely determines the method and response type, so no separate
/// marker type is needed to bind them together. Callers can write
/// `client.request(ThreadStartParams { ... })` without turbofish syntax. This requires a
/// parameter type to belong to only one method; generation fails if the schema violates
/// that rule.
///
/// Methods with `params: null` have no parameter type to implement the trait on, so emit a
/// unit struct for them. Serde serializes unit structs as `null`, matching the protocol.
fn render_requests(
    client_request: &Schema,
    definitions: &BTreeMap<String, Schema>,
) -> Result<(String, Vec<String>)> {
    let overrides: BTreeMap<&str, &str> = RESPONSE_OVERRIDES.iter().copied().collect();
    let variants = client_request
        .one_of
        .as_ref()
        .context("ClientRequest must be a oneOf")?;

    let mut body = String::new();
    let mut listing = String::new();
    let mut surface = Vec::new();
    let mut unmatched = Vec::new();
    let mut owners: BTreeMap<String, String> = BTreeMap::new();
    let mut count = 0usize;

    for variant in variants {
        let properties = match &variant.properties {
            Some(properties) => properties,
            None => continue,
        };
        let Some(method) = properties.get("method").and_then(Schema::const_string) else {
            continue;
        };
        let params_schema = properties.get("params");

        // Parameter type: use `$ref` directly, `{"type":"null"}` for nullary methods,
        // and `anyOf` for optional values. Nullary names come from the method; other names
        // come from the schema. Do not compare names to distinguish these cases:
        // `initialize` actually uses a parameter type named `InitializeParams`.
        let mut nullary = false;
        let params = match params_schema {
            // Missing params or `{"type":"null"}` means a nullary method.
            None => {
                nullary = true;
                format!("{}Params", method_type_name(&method))
            }
            Some(schema) if schema.is_type("null") => {
                nullary = true;
                format!("{}Params", method_type_name(&method))
            }
            Some(schema) => match &schema.reference {
                Some(reference) => reference_name(reference)
                    .map(type_name)
                    .unwrap_or_else(|| "serde_json::Value".to_owned()),
                None => match schema
                    .nullable_inner()
                    .and_then(|inner| inner.reference.as_deref())
                {
                    Some(reference) => format!(
                        "Option<{}>",
                        reference_name(reference)
                            .map(type_name)
                            .unwrap_or_else(|| "serde_json::Value".to_owned())
                    ),
                    None => "serde_json::Value".to_owned(),
                },
            },
        };

        // If two methods share a parameter type, their `impl Request for` blocks conflict.
        // Wrap one type in a newtype or return to marker types; stop instead of silently
        // generating code that does not compile.
        if let Some(previous) = owners.insert(params.clone(), method.clone()) {
            anyhow::bail!(
                "`{previous}` and `{method}` share parameter type `{params}` and cannot each implement Request;\
                 wrap one in a newtype; see docs/protocol-codegen.md"
            );
        }
        // Nullary types are synthesized. A name collision with a schema type would
        // silently shadow it under `use types::*`.
        if nullary && definitions.contains_key(&params) {
            anyhow::bail!(
                "generated nullary parameter type `{params}` for `{method}` conflicts with a schema type of the same name"
            );
        }

        // Infer the response type by convention first, then consult the override table.
        let base = params
            .trim_start_matches("Option<")
            .trim_end_matches('>')
            .trim_end_matches("Params");
        let by_convention = format!("{base}Response");
        let response = if let Some(explicit) = overrides.get(method.as_str()) {
            (*explicit).to_owned()
        } else if definitions.contains_key(&by_convention) {
            by_convention
        } else {
            unmatched.push(method.clone());
            "serde_json::Value".to_owned()
        };

        let doc = doc_comment(variant.description.as_deref(), 0);
        if nullary {
            body.push_str(&format!(
                "{doc}/// Parameters for `{method}`: this method takes no parameters and serializes as `null`.\n\
                 #[derive(Clone, Copy, Debug, Default, Serialize)]\n\
                 pub struct {params};\n\n"
            ));
        }
        body.push_str(&format!(
            "{doc}/// `{method}`\n\
             impl Request for {params} {{\n\
             \x20   const METHOD: &'static str = \"{method}\";\n\
             \x20   type Response = {response};\n\
             }}\n\n"
        ));
        // `Option<T>` is not a linkable name, so render it as code instead.
        if params.contains('<') {
            listing.push_str(&format!("//! - `{method}` → `{params}`\n"));
        } else {
            listing.push_str(&format!("//! - `{method}` → [`{params}`]\n"));
        }
        surface.push(format!("| `{method}` | `{params}` | `{response}` |"));
        count += 1;
    }

    if !unmatched.is_empty() {
        println!(
            "  warning: {} methods have no inferred response type and fall back to serde_json::Value:",
            unmatched.len()
        );
        for method in &unmatched {
            println!("    {method}");
        }
    }
    println!("  Generated {count} client requests");

    Ok((
        format!(
            "{HEADER}//! Parameter types and their corresponding method and response types.\n//!\n\
         //! {count} methods in total:\n\
         //!\n{listing}\n\
         use super::types::*;\n\
         use serde::Serialize;\n\
         use serde::de::DeserializeOwned;\n\n\
         /// A client-to-server request.\n\
         ///\n\
         /// Implemented on the parameter type: the type uniquely determines the method\n\
         /// and response, so `client.request(ThreadStartParams {{ .. }})` has a known\n\
         /// return type without specifying the method separately.\n\
         pub trait Request: Serialize {{\n\
         \x20   const METHOD: &'static str;\n\
         \x20   type Response: DeserializeOwned;\n\
         }}\n\n{body}"
        ),
        surface,
    ))
}

/// Generate a `ServerNotification` / `ServerRequest` oneOf as an enum tagged by method.
fn render_incoming(name: &str, schema: &Schema, doc: &str) -> Result<(String, Vec<String>)> {
    let variants = schema
        .one_of
        .as_ref()
        .with_context(|| format!("{name} must be a oneOf"))?;
    let mut body = String::new();
    let mut surface = Vec::new();
    let mut count = 0usize;

    for variant in variants {
        let Some(properties) = &variant.properties else {
            continue;
        };
        let Some(method) = properties.get("method").and_then(Schema::const_string) else {
            continue;
        };
        let variant_name = method_type_name(&method);
        let variant_doc = doc_comment(variant.description.as_deref(), 1);
        let payload = properties.get("params").and_then(|params| {
            params
                .reference
                .as_deref()
                .and_then(reference_name)
                .map(type_name)
        });
        match &payload {
            Some(ty) => body.push_str(&format!(
                "{variant_doc}    #[serde(rename = \"{method}\")]\n    {variant_name}({ty}),\n"
            )),
            None => body.push_str(&format!(
                "{variant_doc}    #[serde(rename = \"{method}\")]\n    {variant_name},\n"
            )),
        }
        surface.push(format!(
            "| `{method}` | `{}` |",
            payload.as_deref().unwrap_or("(no params)")
        ));
        count += 1;
    }
    println!("  Generated {count} {name} variants");

    Ok((
        format!(
            "/// {doc}\n\
         ///\n\
         /// Contains only the methods known when this client was generated. The server\n\
         /// may add methods at any time, so a parse failure is **not** an error. Callers\n\
         /// should preserve and pass through the original JSON instead of closing the connection.\n\
         #[allow(clippy::large_enum_variant)]\n\
         #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]\n\
         #[serde(tag = \"method\", content = \"params\")]\n\
         pub enum {name} {{\n{body}}}\n"
        ),
        surface,
    ))
}

/// Protocol surface inventory.
///
/// It exists to make diffs easy to review. Regenerate it after a Codex upgrade to see
/// added or removed methods and request parameter/response type changes. Review the
/// `types.rs` diff for field-level changes.
fn surface(
    requests: &[String],
    notifications: &[String],
    server_requests: &[String],
    definitions: &BTreeMap<String, Schema>,
) -> String {
    let mut types: Vec<_> = definitions.keys().map(|name| type_name(name)).collect();
    types.sort();
    types.dedup();
    let type_list = types
        .iter()
        .map(|name| format!("- `{name}`"))
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        "# Protocol surface\n\n\
         Generated by protocol-codegen; do not edit by hand. **This file is for reviewing diffs.**\n\
         Regenerate after a Codex upgrade to see method-level protocol changes.\n\n\
         - Client requests: {}\n\
         - Server notifications: {}\n\
         - Server requests: {}\n\
         - Data types: {}\n\n\
         ## Client requests\n\n\
         | Method | Parameters | Response |\n| --- | --- | --- |\n{}\n\n\
         ## Server notifications\n\n\
         | Method | Payload |\n| --- | --- |\n{}\n\n\
         ## Server requests\n\n\
         These **must be answered**, or the server remains blocked.\n\n\
         | Method | Payload |\n| --- | --- |\n{}\n\n\
         ## Data types\n\n{}\n",
        requests.len(),
        notifications.len(),
        server_requests.len(),
        types.len(),
        requests.join("\n"),
        notifications.join("\n"),
        server_requests.join("\n"),
        type_list,
    )
}

/// For example, `thread/start` maps to `ThreadStart` and
/// `item/agentMessage/delta` maps to `ItemAgentMessageDelta`.
fn method_type_name(method: &str) -> String {
    method.split('/').map(pascal).collect::<Vec<_>>().join("")
}

#[allow(dead_code)]
fn unused(_: fn(&str) -> String) {
    let _ = field_name;
}
